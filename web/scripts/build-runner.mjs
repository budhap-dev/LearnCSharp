/**
 * Publishes the in-browser C# runner to public/runner/<hash>/ and records the path for the app.
 *
 * The folder is named after a hash of what goes into the build, which gives two things:
 *   - Its files never change at a given URL, so they can be cached forever. A deploy can never
 *     leave a browser holding a mix of old and new runtime files.
 *   - An unchanged runner is not rebuilt, so `npm run dev` stays quick.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const project = join(web, '..', 'src', 'LearnCSharp.Runner');
const runnerRoot = join(web, 'public', 'runner');
const generated = join(web, 'src', 'lib', 'runnerPath.generated.ts');

const hash = createHash('sha256');
hash.update(execFileSync('dotnet', ['--version'], { encoding: 'utf8' }));
for (const file of ['LearnCSharp.Runner.csproj', 'Program.cs', 'wwwroot/worker.js']) {
  hash.update(file).update(readFileSync(join(project, file)));
}
const version = hash.digest('hex').slice(0, 12);
const target = join(runnerRoot, version);

if (existsSync(join(target, 'worker.js'))) {
  console.log(`Runner ${version} is already built`);
} else {
  const publish = join(project, 'bin', 'site-publish');
  rmSync(publish, { recursive: true, force: true });
  execFileSync('dotnet', ['publish', project, '-c', 'Release', '-o', publish, '--nologo', '-v', 'q'], { stdio: 'inherit' });

  rmSync(runnerRoot, { recursive: true, force: true });
  mkdirSync(runnerRoot, { recursive: true });
  // Copied under a temporary name, so a build that dies part-way is not mistaken for a finished one.
  const partial = `${target}.partial`;
  cpSync(join(publish, 'wwwroot'), partial, {
    recursive: true,
    // Brotli is smaller and every browser that can run this supports it, so the .gz copies are dead weight.
    filter: (source) => !source.endsWith('.gz'),
  });
  renameSync(partial, target);
  console.log(`Published runner ${version} (${readdirSync(join(target, '_framework')).length} framework files)`);
}

writeFileSync(
  generated,
  `// Generated by scripts/build-runner.mjs - never edit by hand.\nexport const RUNNER_PATH = '/runner/${version}';\n`,
);
